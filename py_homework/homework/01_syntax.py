"""
第 01 天：C 寫法 → Python 寫法（最基本的翻譯）
給有 C 基礎的人   預估 20 分鐘

=================================================================
【對照表：同一件事，兩種寫法】
=================================================================

  C                              Python
  ------------------------------ ------------------------------
  int x = 5;                     x = 5            不宣告型別、不加分號
  { ... }                        用「縮排」分界    ← 唯一要習慣的
  //註解  /*註解*/               # 註解
  true / false                   True / False     ← 大寫開頭！
  NULL                           None
  &&  ||  !                      and  or  not     ← 符號變英文
  i++                            i += 1           ← Python 沒有 ++ ！
  printf("%d\n", x);             print(x)

=================================================================
【坑 1：/ 的行為不一樣（最容易中招）】
=================================================================

  C:       7 / 2  ==  3      兩個 int 相除 -> 砍掉小數
  Python:  7 / 2  ==  3.5    永遠是浮點數！

  想要 C 那種「砍掉小數」的除法，Python 用兩條斜線：
           7 // 2  ==  3
          -7 // 2  == -4     （注意：往小的方向砍，不是往 0 砍）

  你 hw0 寫的 num // 10 % 10 用的就是這個 //

=================================================================
【坑 2：Python 沒有 i++ 也沒有 switch】
=================================================================

  i++;     ->  i += 1      （寫 i++ 會直接語法錯誤）
  i--;     ->  i -= 1
  switch   ->  用 if / elif / else，或用 dict（第 08 天會教）

=================================================================
【爽點：比較可以串起來】
=================================================================

  C:       if (0 < x && x < 100)
  Python:  if 0 < x < 100:        ← 直接這樣寫，合法

=================================================================
【練習】把註解裡的 C 翻成 Python
=================================================================
"""


# --- 第 1 題 ---
# C: int half(int n) { return n / 2; }
# 翻成 Python，且結果要跟 C 一樣（7 -> 3，不是 3.5）
def half(n):
    return n//2



# --- 第 2 題 ---
# C: bool in_range(int x) { return (x >= 0 && x <= 100); }
# 用 Python 的串聯比較寫，只要一行
def in_range(x):
  return x >= 0 and x <= 100


# --- 第 3 題 ---
# C:  int count = 0;
#     for (int i = 1; i <= n; i++) { if (i % 3 == 0) count++; }
#     return count;
# 算 1~n 之間有幾個 3 的倍數
# 提示：Python 的 for 是 for i in range(1, n+1):
def count_multiples_of_3(n):
    count=0
    for i in range(1, n+1):
        if i%3==0:
            count+=1
    return count
            


# --- 第 4 題 ---
# C: 判斷閏年   (year%4==0 && year%100!=0) || year%400==0
# 記得 && || 要換成英文
def is_leap(year):
    if year%4==0 and  year%100!=0 or year%400==0:
      return True
    else:
       return False
    


# =================================================================
print("第1題", "OK" if half(7) == 3 and half(10) == 5 else f"錯，half(7)給了 {half(7)}，應該是 3（不是3.5）")
print("第2題", "OK" if in_range(50) and not in_range(101) and in_range(0) else f"錯，in_range(101)給了 {in_range(101)}，應該是 False")
print("第3題", "OK" if count_multiples_of_3(10) == 3 else f"錯，count_multiples_of_3(10)給了 {count_multiples_of_3(10)}，應該是 3")
print("第4題", "OK" if is_leap(2024) and not is_leap(1900) and is_leap(2000) else f"錯，is_leap(1900)給了 {is_leap(1900)}，應該是 False")
