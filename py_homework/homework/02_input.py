"""
第 02 天：輸入與型別轉換
預估 25 分鐘

=================================================================
【C 的 scanf 幫你做的事，Python 要自己做】
=================================================================

  C:       int n;
           scanf("%d", &n);      <- %d 已經告訴編譯器「這是整數」

  Python:  n = input()           <- 拿到的一定是「字串」！
           n = int(n)            <- 要自己轉

  你筆記第一行就寫了這句，這裡就是在練它：
      input() 讀進來的都是字串，要用 int() float() 轉數字才能算

  合起來寫：
      n = int(input("請輸入數字："))

-----------------------------------------------------------------
【一行讀多個數字：C 要寫兩次 scanf，Python 一行搞定】
-----------------------------------------------------------------

  C:       scanf("%d %d", &a, &b);

  Python:  a, b = input().split()          # 拿到兩個「字串」
           a, b = int(a), int(b)           # 再轉

  更常見的寫法（你 apcs.py 已經用過）：
           a, b = map(int, input().split())

  拆解 map(int, ["3", "5"])：
      map(函數, 資料)  =  把「函數」套到「資料」裡每一個東西上
      map(int, ["3","5"])  ->  3, 5
      要變成 list 就再包 list(...)

-----------------------------------------------------------------
【爽點：Python 可以一行交換，不用 temp】
-----------------------------------------------------------------

  C:       int t = a; a = b; b = t;
  Python:  a, b = b, a          ← 你 pointerswap.c 寫的那整個函式，一行

=================================================================
【練習】這裡不用 input（不然沒法自動測），改成傳字串進來
=================================================================
"""


# --- 第 1 題 ---
# 傳進來 "3 5"，回傳兩個數字的和（8）
# 提示：s.split() 會切成 ["3", "5"]
def add_from_text(s):
    
    return sum(map(int,s.split()))


# --- 第 2 題 ---
# 傳進來 "3 1 4 1 5"，回傳最大的數字（5）
# 提示：先用 map(int, s.split()) 轉成數字，再 max()
def max_from_text(s):
    
    return max(map(int,s.split()))

# --- 第 3 題 ---
# 傳進來 "1,2,3"（逗號分隔），回傳總和 6
# 提示：你筆記寫過 .split(",") 遇到逗號就切開
def sum_csv(s):
    return sum(map(int,s.split(",")))


# --- 第 4 題 ---
# 交換：傳進 (a, b) 回傳 (b, a)。用 Python 的一行寫法
def swap(a, b):
    return b , a


# =================================================================
print("第1題", "OK" if add_from_text("3 5") == 8 else f"錯，給了 {add_from_text('3 5')}，應該是 8")
print("第2題", "OK" if max_from_text("3 1 4 1 5") == 5 else f"錯，給了 {max_from_text('3 1 4 1 5')}，應該是 5")
print("第3題", "OK" if sum_csv("1,2,3") == 6 else f"錯，給了 {sum_csv('1,2,3')}，應該是 6")
print("第4題", "OK" if swap(1, 2) == (2, 1) else f"錯，給了 {swap(1, 2)}，應該是 (2, 1)")
