# --- 第 1 題 ---
# 回傳 list 的最後一個元素。用負索引，不要用 len()
def last(nums):
    return nums[-1]


# --- 第 2 題 ---
# 回傳「前三個元素」組成的新 list。不足三個就有幾個給幾個。
# 提示：切片超出範圍不會爆，會自己截斷
def first_three(nums):
    return nums[:3]


# --- 第 3 題 ---
# 回傳一個「排序好的新 list」，而且原本那個不可以被改到
def sorted_copy(nums):
    return sorted(nums)


# --- 第 4 題 ---
# 傳入 n，回傳 [1, 2, 3, ..., n] 這個 list
# 用 append 做（先開空 list，再 for 迴圈 append）
def build_list(n):
    answer=[]
    for i in range(1,n+1):
        answer.append(i)
    return answer


# --- 第 5 題 ---
# 回傳「去掉重複、由小到大排好」的新 list
# 提示：你筆記寫過 set(num) 刪除重複的。set 是無序的，記得再 sorted()
def unique_sorted(nums):
    return sorted(set(nums))


# =================================================================
_a = [3, 1, 2]
_b = sorted_copy(_a)
print("第1題", "OK" if last([1, 2, 3]) == 3 else f"錯，給了 {last([1,2,3])}，應該是 3")
print("第2題", "OK" if first_three([1,2,3,4,5]) == [1,2,3] and first_three([9]) == [9] else f"錯，給了 {first_three([1,2,3,4,5])}，應該是 [1,2,3]")
print("第3題", "OK" if _b == [1,2,3] and _a == [3,1,2] else f"錯，給了 {_b}（原本的list現在是 {_a}，不該被改）")
print("第4題", "OK" if build_list(4) == [1,2,3,4] and build_list(0) == [] else f"錯，給了 {build_list(4)}，應該是 [1,2,3,4]")
print("第5題", "OK" if unique_sorted([3,1,3,2,1]) == [1,2,3] else f"錯，給了 {unique_sorted([3,1,3,2,1])}，應該是 [1,2,3]")
