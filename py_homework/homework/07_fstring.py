"""
第 07 天：f-string —— 取代 printf 的格式化
預估 15 分鐘（輕鬆的一天）

=================================================================
【printf vs f-string】
=================================================================

  C:       printf("bmi = %.3f\n", bmi);
  Python:  print(f"bmi = {bmi:.3f}")

  規則：字串前面加 f，變數用 { } 包起來，格式寫在冒號後面。

  C 格式             f-string            結果（x = 3.14159, n = 42）
  -----------------  ------------------  --------------------------
  %d                 {n}                 42
  %.2f               {x:.2f}             3.14
  %5d   (寬度5靠右)  {n:5d}  或 {n:>5}       42
  %-5d  (靠左)       {n:<5}              42
  (置中，C 沒有)     {n:^5}               42
  %05d  (補0)        {n:05d}             00042
  %%                 {{ }}               印出大括號本身

  { } 裡面可以直接算式：
      print(f"總和 {a + b}")
      print(f"平均 {total / len(nums):.2f}")

-----------------------------------------------------------------
【print 的兩個參數（你筆記記過）】
-----------------------------------------------------------------

  print 預設會換行、多個東西用空白隔開：

      print("a", "b")               ->  a b
      print("a", "b", sep=",")      ->  a,b        改分隔符
      print("3.14", end=" ")        ->  不換行     改結尾

  C 的 printf 本來就不換行，所以 Python 想模仿就用 end=""。
  你 Pascaltriangle 就是用 end="" 做的。

=================================================================
【練習】這幾題回傳「字串」，不要 print
=================================================================
"""


# --- 第 1 題 ---
# 把 bmifunction.c 的輸出翻成 Python
# 回傳 "bmi = 22.857"（小數三位）
def bmi_text(height_cm, weight_kg):
    
    return f"bmi = {weight_kg/(height_cm*0.01*height_cm*0.01):.3f}"


# --- 第 2 題 ---
# 回傳 "45.0%"（百分比，小數一位）
# score_report(9, 20) -> "45.0%"
def score_report(got, total):
    return f"{got/total*100:.1f}%"


# --- 第 3 題 ---
# 回傳靠右對齊、寬度 5 的字串
# right_align(42) -> "   42"
def right_align(n):
    return f"{n:>5}"


# --- 第 4 題 ---
# 把 list 印成一行，用 " | " 隔開
# join_row([1, 2, 3]) -> "1 | 2 | 3"
# 提示：join 只能黏字串，數字要先轉：用 for 或 map(str, nums)
def join_row(nums):
    return " | ".join(map(str,nums))


# =================================================================
print("第1題", "OK" if bmi_text(175, 70) == "bmi = 22.857" else f"錯，給了 {bmi_text(175,70)!r}，應該是 'bmi = 22.857'")
print("第2題", "OK" if score_report(9, 20) == "45.0%" else f"錯，給了 {score_report(9,20)!r}，應該是 '45.0%'")
print("第3題", "OK" if right_align(42) == "   42" else f"錯，給了 {right_align(42)!r}，應該是 '   42'")
print("第4題", "OK" if join_row([1,2,3]) == "1 | 2 | 3" else f"錯，給了 {join_row([1,2,3])!r}，應該是 '1 | 2 | 3'")
